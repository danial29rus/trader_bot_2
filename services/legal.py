from html import escape

from config import Settings


def _date(settings: Settings) -> str:
    return escape(settings.legal_document_date)


def _operator(settings: Settings) -> str:
    if settings.legal_operator_name.strip():
        return escape(settings.legal_operator_name)
    return f"Администрация сервиса {escape(settings.store_name)}"


def _contact(settings: Settings) -> str:
    channels = ["раздел «Поддержка» в боте"]
    if settings.has_public_support_contact:
        channels.append(escape(settings.support_contact))
    if settings.legal_contact_email.strip():
        channels.append(escape(settings.legal_contact_email))
    return ", ".join(channels)


def _seller(settings: Settings) -> str:
    if settings.legal_seller_details.strip():
        return escape(settings.legal_seller_details)
    # Environment-variable names are implementation details and must never
    # appear in customer-facing legal text.
    return "будет указан до подключения приёма оплаты"


def _payment_status(settings: Settings) -> str:
    if settings.payments_enabled and settings.legal_provider_name.strip():
        return f"Оплата проводится только на защищённой странице платёжного провайдера {escape(settings.legal_provider_name)}."
    return "Приём оплаты сейчас не подключён: Сервис не создаёт счёт и не принимает переводы в сообщениях."


def _links(settings: Settings) -> str:
    if not settings.legal_public_base_url.strip():
        return "Актуальные версии также доступны в разделе «Документы» бота."
    base = escape(settings.legal_public_base_url.rstrip("/"))
    return f'Публичные версии: <a href="{base}/privacy.html">конфиденциальность</a>, <a href="{base}/agreement.html">соглашение</a>, <a href="{base}/offer.html">оферта</a>, <a href="{base}/returns.html">возвраты</a>, <a href="{base}/contacts.html">контакты</a>, <a href="{base}/prices.html">цены</a>.'


def privacy_policy(settings: Settings) -> str:
    return f"""<b>Политика конфиденциальности</b>
Редакция от {_date(settings)}

<b>1. Общие положения</b>
Настоящая Политика определяет порядок обработки данных пользователей Telegram-бота {escape(settings.store_name)} (далее — Сервис). Оператор: {_operator(settings)}.

Используя Сервис, пользователь подтверждает, что ознакомился с Политикой. Если пользователь не согласен с ней, следует прекратить использование Сервиса.

<b>2. Какие данные обрабатываются</b>
Сервис получает из Telegram идентификатор аккаунта и чата, имя, username и язык (если они доступны), а также сохраняет сообщения, нажатия в боте, состав корзины, игровые ID/UID и сервер, сведения о заказах, избранное/настройки и текст обращений в поддержку. Эти данные нужны для работы каталога, личного кабинета, поддержки и истории заказов.

Сервис не запрашивает и не хранит реквизиты банковских карт, CVV/CVC, пароли или коды подтверждения. Не отправляйте такие данные в поддержку.

<b>3. Цели и передача данных</b>
Данные используются для работы Сервиса, ответа на обращения, предотвращения двойной обработки и исполнения обязательств по заказу. Они не продаются и не используются для рекламных рассылок. Telegram обрабатывает данные в соответствии со своими правилами. {_payment_status(settings)} Сервис не получает и не хранит реквизиты банковских карт.

Доступ к данным имеют только администраторы и операторы поддержки в необходимом объёме. Для исполнения оплаченного заказа игровая идентификация передаётся поставщику {escape(settings.legal_supplier_name)}; платёжному провайдеру передаются только данные, необходимые для платежа (номер заказа, сумма, валюта и описание). Данные могут быть предоставлены государственным органам при законном требовании.

<b>4. Хранение и защита</b>
Данные хранятся не дольше, чем это требуется для указанных целей и обязательных сроков по применимому законодательству. Удаление по запросу может не затронуть записи о платежах, обращения в поддержку, переписку Telegram и резервные копии, если их хранение необходимо для учёта, спора или безопасности. Администрация применяет организационные и технические меры защиты, однако передача данных через интернет не может гарантировать абсолютную безопасность.

<b>5. Обращения и изменения</b>
Запрос по данным, исправлению, ограничению или удалению можно направить через {_contact(settings)}; для защиты аккаунта может потребоваться подтверждение владения им. Новая редакция публикуется в Сервисе с указанием даты. {_links(settings)}"""


