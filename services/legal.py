from html import escape

from config import Settings


def _date(settings: Settings) -> str:
    return escape(settings.legal_document_date)


def _operator(settings: Settings) -> str:
    if settings.legal_operator_name.strip():
        return escape(settings.legal_operator_name)
    return f"Администрация сервиса {escape(settings.store_name)}"


def _contact(settings: Settings) -> str:
    channels = ["раздел «Поддержка» в боте"]
    if settings.has_public_support_contact:
        channels.append(escape(settings.support_contact))
    if settings.legal_contact_email.strip():
        channels.append(escape(settings.legal_contact_email))
    return ", ".join(channels)


def privacy_policy(settings: Settings) -> str:
    return f"""<b>Политика конфиденциальности</b>
Редакция от {_date(settings)}

<b>1. Общие положения</b>
Настоящая Политика определяет порядок обработки данных пользователей Telegram-бота {escape(settings.store_name)} (далее — Сервис). Оператор: {_operator(settings)}

Используя Сервис, пользователь подтверждает, что ознакомился с Политикой. Если пользователь не согласен с ней, следует прекратить использование Сервиса.

<b>2. Какие данные обрабатываются</b>
Сервис получает из Telegram идентификатор аккаунта, имя и username (если они доступны), а также сохраняет состав корзины, сведения о заказах и текст обращений в поддержку. Эти данные нужны для работы каталога, личного кабинета, поддержки и истории заказов.

Сервис не запрашивает и не хранит реквизиты банковских карт, CVV/CVC, пароли или коды подтверждения. Не отправляйте такие данные в поддержку.

<b>3. Цели и передача данных</b>
Данные используются для работы Сервиса, ответа на обращения, предотвращения злоупотреблений и исполнения обязательств по заказу. Telegram обрабатывает данные в соответствии со своими правилами. Платёжные данные обрабатываются на защищённой стороне платёжного провайдера; Сервис не получает и не хранит реквизиты банковских карт.

<b>4. Хранение и защита</b>
Данные хранятся не дольше, чем это требуется для указанных целей и обязательных сроков по применимому законодательству. Администрация применяет организационные и технические меры защиты, однако передача данных через интернет не может гарантировать абсолютную безопасность.

<b>5. Обращения и изменения</b>
Запрос по данным, исправлению или удалению можно направить через {_contact(settings)}. Новая редакция публикуется в Сервисе с указанием даты; продолжение использования после публикации означает ознакомление с новой редакцией."""


def terms_of_service(settings: Settings) -> str:
    return f"""<b>Пользовательское соглашение</b>
Редакция от {_date(settings)}

<b>1. Предмет</b>
Настоящее соглашение регулирует использование Telegram-бота {escape(settings.store_name)} (далее — Сервис). Администрация: {_operator(settings)}. Запуск бота и использование его функций означает ознакомление с соглашением; при несогласии пользователь прекращает использование Сервиса.

<b>2. Каталог и цифровые товары</b>
Сервис показывает цифровые товары: игры Steam и подарочные карты. До добавления в корзину пользователь самостоятельно проверяет название, платформу, регион, способ активации, наличие и цену. Эти характеристики показываются в карточке товара и могут обновляться поставщиком.

<b>3. Цены и оформление</b>
Цена каждого товара указана в его карточке, а итоговая стоимость — в корзине до перехода к оплате. Отдельная комиссия Сервиса к показанной итоговой сумме не добавляется. До подтверждения заказа пользователь видит его состав, итоговую сумму, применённую скидку и сведения о товаре.

<b>4. Оплата, исполнение и возвраты</b>
Пользователь до подтверждения платежа видит окончательную сумму, способ оплаты, правила исполнения и контакты поддержки. Выдача цифрового товара производится только после подтверждения оплаты и при наличии товара у поставщика. Вопросы об ошибке выдачи или возврате рассматриваются через {_contact(settings)} с номером заказа; права потребителя, предоставленные применимым законодательством, не ограничиваются настоящим соглашением.

<b>5. Правила использования</b>
Пользователь обязуется использовать собственный Telegram-аккаунт, не передавать доступ третьим лицам, не пытаться нарушить работу Сервиса и не использовать его для противоправных действий. Администрация вправе ограничить доступ при злоупотреблениях, требованиях закона или платёжного провайдера.

<b>6. Изменения и связь</b>
Актуальная редакция всегда доступна в разделе «Документы». Вопросы по работе Сервиса направляются через {_contact(settings)}."""


